def normalize_town(value):
    value = str(value or "").strip()
    aliases = {
        "minsk": "Минск",
        "мінск": "Минск",
        "могилев": "Могилёв",
        "mogilev": "Могилёв",
        "gomel": "Гомель",
        "гомель": "Гомель",
        "grodno": "Гродно",
        "brest": "Брест",
        "vitebsk": "Витебск",
    }
    return aliases.get(value.casefold(), value)
